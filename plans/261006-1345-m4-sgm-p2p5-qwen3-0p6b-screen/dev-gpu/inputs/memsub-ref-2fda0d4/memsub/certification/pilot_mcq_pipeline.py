"""B.3 pilot MCQ pipeline (1-2k items only — the full corpus is a later,
human-triggered step; BUILD.md 3).

Items are extractive MCQs generated by the base model from ~1k-token
sub-chunks. Filters: (a) teacher-verified answerable WITH context,
(b) discarded if answerable WITHOUT context — filter (b) makes every item a
counterfactual probe. eq_policy_v1 = answer-letter exact match (spec 17.4).
"""

from __future__ import annotations

import json
import random
import re
from dataclasses import asdict, dataclass


def eq_policy_v1(predicted_letter: str, gold_letter: str) -> bool:
    return predicted_letter.strip().upper()[:1] == gold_letter.strip().upper()[:1]


@dataclass
class McqItem:
    item_id: str
    doc_id: str
    chunk_token_start: int
    chunk_token_end: int
    question: str
    options: list[str]
    gold_letter: str
    eq_policy: str = "eq_policy_v1"


_GEN_PROMPT = (
    "Below is a passage. Write ONE multiple-choice question that can only be "
    "answered by reading this passage (an exact fact: a name, number, or "
    "identifier). Give 4 options A-D and mark the correct letter.\n"
    "Format exactly:\nQ: <question>\nA: <option>\nB: <option>\nC: <option>\n"
    "D: <option>\nANSWER: <letter>\n\nPassage:\n{chunk}")


def parse_mcq(text: str):
    q = re.search(r"Q:\s*(.+)", text)
    opts = re.findall(r"^([A-D]):\s*(.+)$", text, re.MULTILINE)
    ans = re.search(r"ANSWER:\s*([A-D])", text)
    opts = [o for letter, o in opts if letter in "ABCD"][:4]
    if not (q and ans and len(opts) == 4):
        return None
    return q.group(1).strip(), opts, ans.group(1)


class PilotMcqPipeline:
    def __init__(self, runtime, chunk_tokens: int = 1024, seed: int = 0):
        self.runtime = runtime
        self.chunk_tokens = chunk_tokens
        self.rng = random.Random(seed)

    def _chunks(self, doc_text: str, doc_id: str, per_doc: int):
        ids = self.runtime.tokenizer.encode(doc_text, add_special_tokens=False)
        if len(ids) < self.chunk_tokens:
            return
        for _ in range(per_doc):
            start = self.rng.randrange(0, len(ids) - self.chunk_tokens + 1)
            chunk_ids = ids[start:start + self.chunk_tokens]
            yield start, start + self.chunk_tokens, self.runtime.tokenizer.decode(chunk_ids)

    def generate(self, docs: dict[str, str], target_items: int,
                 per_doc: int = 4) -> list[McqItem]:
        items: list[McqItem] = []
        for doc_id, text in docs.items():
            for start, end, chunk in self._chunks(text, doc_id, per_doc):
                if len(items) >= target_items:
                    return items
                raw = self.runtime.generate_text(
                    [{"role": "user", "content": _GEN_PROMPT.format(chunk=chunk)}],
                    max_new_tokens=200)
                parsed = parse_mcq(raw)
                if parsed is None:
                    continue
                question, options, gold = parsed
                item = McqItem(
                    item_id=f"mcq_{doc_id}_{start}_{len(items)}",
                    doc_id=doc_id, chunk_token_start=start, chunk_token_end=end,
                    question=question, options=options, gold_letter=gold)
                # filter (a): teacher answers correctly WITH context
                with_ctx = self.runtime.answer_letter(chunk, question, options)
                if not eq_policy_v1(with_ctx, gold):
                    continue
                # filter (b): discard if answerable WITHOUT context
                without_ctx = self.runtime.answer_letter("", question, options)
                if eq_policy_v1(without_ctx, gold):
                    continue
                items.append(item)
        return items

    @staticmethod
    def save(items: list[McqItem], path: str) -> None:
        with open(path, "w") as f:
            json.dump([asdict(i) for i in items], f, indent=1)

    @staticmethod
    def load(path: str) -> list[McqItem]:
        with open(path) as f:
            return [McqItem(**d) for d in json.load(f)]
